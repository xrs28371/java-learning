public class Demo03 {
    public static void main(String[] args)
    {
        //变量定义格式
        // 数据类型 变量名 = 变量值
        int a=10;
        System.out.println(a);

        //修改变量
        a=20;
        System.out.println(a);

        //定义byte类型的变量
        byte b=10;
        System.out.println(b);

        //定义short类型的变量
        short c=100;
        System.out.println(c);

        //定义int类型
        int d=10;
        System.out.println(d);

        //定义char类型
        char e='a';
        System.out.println(e);

        //定义boolean类型变量
        boolean f=true;
        System.out.println(f);

        //定义long类型的变量
        long h=1000000000000000000L;
        System.out.println(h);

        //定义double类型的变量
        double i=13.14;
        System.out.println(i);

        //java是强类型的语言
        //long类型防止过大加L
        //float类型不兼容加F


        //标识符的定义规则
        //由数字，字符，下幻想(-)和美元符号($)组成的
        //不能数字开头
        //不能是关键字
        //区分大小写

        


    }
}
