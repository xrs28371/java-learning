public class Demo07 {
    public static void main(String[] args) {
        //关系运算符
        // ==  判断是否相等 成立为ture
        //！= 是否不相等
        //> 是否大于
        //>= 是否大于等于
        //< 是否小于
        //<= 是否小于等于

        int i=10;
        int j=20;
        int k=10;

        System.out.println(i==j);
        System.out.println(i==k);

        //!=
        System.out.println(i!=j);
        System.out.println(i!=k);

        //>
        System.out.println(i>k);
        System.out.println(i>j);

        //>=
        System.out.println(i>=j);
        System.out.println(i>=k);

        //<
        System.out.println(i<k);
        System.out.println(i<j);

        //<=
        System.out.println(i<=k);
        System.out.println(i<=j);


    }
}
